/**
 * 生成文案（模板启发式，示例）。
 * 会结合：热点选题(topic) + 用户创作风格(style) + 受众(audience) 产出对应稿件，
 * 并做合规软过滤。
 * TODO(backend): 替换为 LLM 调用，按 reference 风格 + direction 生成接近质量的真文案，
 *   并叠加内容安全审核 API。
 */
export function generateCopy(b: CopyBrief): GeneratedCopy {
  const d = (b.topic || b.direction || "这个方向").trim();
  const hook = HOOK_TPL[b.type](d);
  const body = BODY_TPL[b.type](d);
  const flavor = b.style && STYLE_FLAVOR[b.style] ? STYLE_FLAVOR[b.style] : null;
  const cta = flavor ? flavor.closer : CTA_TPL[b.type];

  const legal = checkLegal([b.topic || "", b.direction || "", b.reference || ""].join(" "));

  const ctx = [
    b.topic ? `（热点选题：${b.topic}）` : "",
    b.style ? `（文风：${b.style}${flavor ? " · " + flavor.tone : ""}）` : "",
    b.audience ? `（受众：${b.audience}）` : "",
    b.constraints && b.constraints.length
      ? `（拆解约束：${b.constraints.join(" / ")}）`
      : "",
  ]
    .filter(Boolean)
    .join(" ");

  const refNote = b.reference?.trim()
    ? "（已参考你提供的原文风格，提取了开篇节奏与情绪走向）"
    : `（未提供参考文案，已按「${b.type}」通用爆款结构生成）`;

  const legalNote = legal.flagged
    ? `⚠️ 合规提示：检测到可能涉及${legal.hits.join("、")}的内容，请核实信息来源、遵守法律法规与平台规范，勿传播未经证实的信息。`
    : "";

  const full = [
    ctx ? `【上下文】${ctx}` : "",
    `【钩子】${hook}`,
    `【正文】`,
    ...body.map((x) => `· ${x}`),
    `【结尾】${cta}`,
    ``,
    `— 生成说明：${refNote} 示例文案 · 待接 LLM 后按参考质量输出`,
    legalNote,
  ]
    .filter(Boolean)
    .join("\n");

  return { hook, body, cta, full, legal, styleNote: flavor?.tone };
}
