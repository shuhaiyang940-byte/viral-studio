export type CopyType = "口播" | "种草" | "剧情" | "知识" | "测评" | "带货";

export const COPY_TYPES: CopyType[] = ["口播", "种草", "剧情", "知识", "测评", "带货"];

export interface CopyBrief {
  reference?: string; // 参考视频文案（粘贴 / 抓取的原文），可选
  topic?: string; // 热点选题（来自热点追踪），可选
  direction: string; // 用户的新方向 / 主题（兜底）
  type: CopyType;
  tone?: string; // 语气偏好，可选
  style?: string; // 创作风格（来自用户档案：严谨客观 / 轻松幽默 ...）
  audience?: string; // 目标受众（来自用户档案）
  /** 来自「新闻拆解」面板的反馈型提问答案，用于约束文案细节 */
  constraints?: string[];
}

/**
 * 新闻拆解中的单道反馈题。
 * 支持子问题（sub），用于主题下的追问维度（如主问题选完后展开更细的选项）。
 */
export interface CopyFeedbackQuestion {
  id: string;
  q: string;
  options: string[];
  /** 追问子问题（可选） */
  sub?: CopyFeedbackQuestion[];
}

