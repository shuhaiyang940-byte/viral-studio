/**
 * AI 新闻拆解：根据标题文本自动检测主题 → 返回动态反馈提问 + 针对性文案建议。
 *
 * 匹配算法：
 *   1. 遍历所有 NEWS_THEMES，计算每个主题的关键词命中数（长词优先加权）
 *   2. 取得分最高的主题作为检测结果
 *   3. 若所有主题均未命中（得分为 0），返回 FALLBACK_THEME（通用热点）
 *
 * @param topic  - 新闻标题文本
 * @param cat    - 已知的分类标签（可选，用于辅助校验）
 */
export interface NewsAnalysis {
  /** 检测到的主题 */
  theme: NewsTheme;
  /** 该主题下的主问题 + 子问题（展平为 UI 可渲染列表） */
  questions: CopyFeedbackQuestion[];
  /** 针对该标题的文案建议（已嵌入标题内容） */
  suggestions: string[];
  /** 主题标签（用于 UI 展示，如 "📋 政策法规"） */
  themeLabel: string;
}

export function analyzeNewsTopic(topic: string, cat?: string): NewsAnalysis {
  const t = (topic || "").trim();
  if (!t) {
    return {
      theme: FALLBACK_THEME,
      questions: [FALLBACK_THEME.questions],
      suggestions: FALLBACK_THEME.suggestions(t),
      themeLabel: FALLBACK_THEME.label,
    };
  }

  // 计算每个主题的匹配得分
  let bestTheme: NewsTheme = FALLBACK_THEME;
  let bestScore = 0;

  for (const theme of NEWS_THEMES) {
    let score = 0;
    for (const kw of theme.keywords) {
      if (t.includes(kw)) {
        // 长关键词（如"官宣恋情"）比短词（如"官宣"）权重更高，减少误匹配
        score += kw.length >= 3 ? 2 : 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestTheme = theme;
    }
  }

  // 展平问题：主问题 + 子问题
  const flatQuestions: CopyFeedbackQuestion[] = [bestTheme.questions];
  if (bestTheme.questions.sub) {
    flatQuestions.push(...bestTheme.questions.sub);
  }

  return {
    theme: bestTheme,
    questions: flatQuestions,
    suggestions: bestTheme.suggestions(t),
    themeLabel: bestTheme.label,
  };
}

